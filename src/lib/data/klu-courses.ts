export function searchKLUCourses(query: string, limit = 25): KLUCourse[] {
  if (!query || query.trim() === '') return KLU_COURSES.slice(0, limit);
  const q = query.toLowerCase().trim();
  return KLU_COURSES.filter(
    (c) =>
      c.code.toLowerCase().includes(q) ||
      c.name.toLowerCase().includes(q) ||
      c.acronym.toLowerCase().includes(q) ||
      c.department.toLowerCase().includes(q)
  ).slice(0, limit);
}

export function getKLUCourseByCode(code: string): KLUCourse | undefined {
  return KLU_COURSES.find((c) => c.code.toLowerCase() === code.toLowerCase());
}

export function getTermsForBatchTrack(batch: string, track: string): string[] {
  const found = KLU_BATCH_CONFIGS.find(
    (cfg) => cfg.batch === batch && (track === 'All' || cfg.track === track)
  );
  if (found) return found.terms;
  if (batch === 'Y26' || (batch === 'Y25' && track === 'Honours PBL')) {
    return [
      'Tri-Sem 1 (T1)', 'Tri-Sem 2 (T2)', 'Tri-Sem 3 (T3)',
      'Tri-Sem 4 (T4)', 'Tri-Sem 5 (T5)', 'Tri-Sem 6 (T6)',
      'Tri-Sem 7 (T7)', 'Tri-Sem 8 (T8)', 'Tri-Sem 9 (T9)',
      'Tri-Sem 10 (T10)', 'Tri-Sem 11 (T11)', 'Tri-Sem 12 (T12)',
    ];
  }
  return ['Sem 1', 'Sem 2', 'Sem 3', 'Sem 4', 'Sem 5', 'Sem 6', 'Sem 7', 'Sem 8'];
}
